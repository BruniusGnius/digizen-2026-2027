        <h2 class="wf-9" id="beat-1-title">
          <span class="wf-10">Nadie te enseñó esto.</span>
          A ti tampoco te lo enseñaron.
        </h2>
        <p class="wf-11">Respira un segundo.</p>
        <div class="wf-12">
          <p class="wf-13">Si llegaste aquí, probablemente fue después de otra noche rara — de esas en que le dices "ya, deja el cel" por quinta vez y algo dentro de ti se aprieta. No porque él te ignoró. Porque tú no supiste qué más hacer.</p>
          <p class="wf-13">Y quizá una vocecita te susurró lo de siempre: <em>"soy un mal papá."</em> No lo eres.</p>
          <p class="wf-13">A ti te tocó un mundo de calles y bicicletas. A tu hijo le tocó uno que se inventa cada mañana, que nadie te enseñó a leer, y que cambió las reglas mientras tú trabajabas para darle de comer. Nadie te dio el manual. Tampoco a tu mamá. Tampoco al papá de junto.</p>
          <p class="wf-13">Y sí — tú también andas pegado al tuyo. Eso no te hace hipócrita. Te hace humano, atrapado en la misma corriente que se lleva a tu hijo. Que se te haya ido de las manos no te hace mal padre. Lo raro sería que quitarle el aparato <em>hubiera</em> funcionado.</p>
        </div>
        <blockquote class="wf-14">Suéltate la culpa. La vas a necesitar libre para lo que sigue.</blockquote>
